-- ============================================================
-- 報告要自己記住它沒有涵蓋什麼，以及要去弄什麼資料
-- 全部 IF NOT EXISTS，重複執行不會出錯
-- ============================================================
--
-- 規格把「這份沒有涵蓋什麼」列為**必要區塊、不可摺疊**，理由寫在 PRD 也寫在
-- 本專案的交接文件裡：敘述永遠讀起來合理，警語才是決定該信多少的東西。
-- 而 W9 的守門確實算出了那些數字——全文取得率、幾個方向沒驗過新穎性、
-- 幾個因為被判已做過而被排除。
--
-- **但那些數字沒有被存到任何地方。** 它們只活在 n8n 的執行輸出裡：
-- `health_metric` 只吃 `numeric`，存不了「被排除的是哪幾個」這種清單。
-- 執行紀錄會過期、會被清掉，而報告會留下來。結果是一份看起來完整的報告，
-- 而它的警語在產出當下就消失了——這正是這個系統一直在防的那種失效：
-- **少掉的那一半在輸出上看不出來。**
--
-- 同一個問題也發生在「不經模型的取得清單」上。它旁邊掛著一顆藥丸寫著
-- 「直接從資料庫產生，不經模型」，而它同樣沒被存下來。事後從 feasibility
-- 重新拉會得到**現在**的分級，不是**報告產出當下**的那一份——
-- 而 `report` 表刻意把 `tier` 和 `rank` 抄寫而非參照，理由正是這個。

ALTER TABLE report ADD COLUMN IF NOT EXISTS caveats jsonb;
ALTER TABLE report ADD COLUMN IF NOT EXISTS acquisition jsonb;

-- 判決也一起抄寫，理由跟 tier / rank 一樣。報告的新穎性那一節是照著
-- **某一次**對抗式檢查寫的；那次檢查之後可以重跑，而重跑之後
-- 「參照」出來的判決就會跟報告內文說的不一樣，卻沒有任何東西會報錯。
ALTER TABLE report ADD COLUMN IF NOT EXISTS novelty_verdict text;

COMMENT ON COLUMN report.caveats IS
    '這一次執行的實際限制，產出當下由 lib/report.py 從資料庫算出來、'
    '不接受呼叫端傳入。四項：全文取得率、沒驗過新穎性的方向數、'
    '因為被判已做過而排除的方向（要點名）、辯論輪數與未解決反對。';

COMMENT ON COLUMN report.acquisition IS
    '不經模型的取得清單，從 feasibility 抄寫而非參照。'
    '模型寫在 sections.feasibility 的那份是給人讀的散文，會漏；'
    '這一份不會，因為沒有東西重述它。兩份不一致時以這一份為準。';
