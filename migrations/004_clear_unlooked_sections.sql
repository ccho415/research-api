-- ============================================================
-- 清掉「沒查過卻被記成查過」的段落快取
-- ============================================================
--
-- paper_section 裡 content 為 NULL 的語意是「查過了，這篇沒有可取得的全文」，
-- 用來避免下一次採集對同一批論文重抓。
--
-- 但第一版的採集迴圈只在論文有 PMID 時才去解析 PMCID，沒有識別碼的直接跳過
-- ——卻仍然寫了一筆 NULL。那等於替一篇從來沒被查詢過的論文宣稱「查過了，沒有」。
--
-- 危害不在那一筆錯誤本身，而在於它會擋住修正：改成也能用 DOI 解析之後，
-- 這些論文會因為「已經有快取」而被永久跳過。
--
-- 刪除條件是 content IS NULL 且 pmcid IS NULL，也就是「宣稱沒有全文、但我們
-- 手上根本沒有指向全文的鍵」。這也會刪掉少數真的查過、確實沒有 PMCID 的論文，
-- 它們下次會被重查一次——一次請求換掉一個會靜默永久生效的錯誤，划算。
DELETE FROM paper_section ps
USING paper p
WHERE ps.paper_id = p.id
  AND ps.content IS NULL
  AND p.pmcid IS NULL;
